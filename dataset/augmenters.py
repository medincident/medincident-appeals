def apply_synonyms(text: str, rng: random.Random, p_word: float = 0.35) -> str:
    """Fix #1: вероятностная замена синонима (вместо детерминированной)."""
    for word, syns in SYNONYMS.items():
        if word in text and rng.random() < p_word:
            text = text.replace(word, rng.choice(syns), 1)
    return text


def apply_colloquial(text: str, rng: random.Random) -> str:
    """Fix #7: вставка в СЛУЧАЙНУЮ позицию между словами, а не в начало."""
    tokens = text.split(" ")
    if len(tokens) < 3:
        # слишком коротко — вставляем в начало
        return rng.choice(COLLOQUIAL_INSERTS) + " " + text
    pos = rng.randrange(1, len(tokens))
    tokens.insert(pos, rng.choice(COLLOQUIAL_INSERTS))
    return " ".join(tokens)


def apply_style(core: str, rng: random.Random) -> str:
    """Fix #6: стиль применяется к ядру и ЗАМЕНЯЕТ обычные обёртки.
    Вызывающий код не должен добавлять PREAMBLE/SUFFIX поверх."""
    prefix, suffix = rng.choice(STYLE_WRAPPERS)
    return prefix + core + suffix


def apply_fixed_typos(text: str, rng: random.Random, p: float = 0.30) -> str:
    """Фиксированные фонетические/типовые ошибки."""
    for src, dst in TYPO_REPLACEMENTS:
        if src in text and rng.random() < p:
            text = text.replace(src, dst, 1)
    return text


def _typo_char(ch: str, rng: random.Random) -> str:
    """Сгенерировать опечатку для одного символа."""
    op = rng.random()
    if op < 0.4:  # substitute на QWERTY-соседа
        neighbors = _QWERTY_NEIGHBORS.get(ch.lower())
        if neighbors:
            return rng.choice(neighbors)
        return ch
    elif op < 0.7:  # delete
        return ""
    elif op < 0.85:  # swap с собой (duplicate)
        return ch + ch
    else:  # вставка соседа
        neighbors = _QWERTY_NEIGHBORS.get(ch.lower())
        if neighbors:
            return ch + rng.choice(neighbors)
        return ch


def apply_qwerty_typos(text: str, rng: random.Random, p_char: float = 0.015) -> str:
    """Fix #5: генеративные опечатки на уровне символов.
    p_char — вероятность ошибки в одном символе. 0.015 ≈ 1-2 ошибки на 100 символов.
    Работает только на кириллице; остальные символы не трогаем.
    """
    out: list[str] = []
    for ch in text:
        if "а" <= ch.lower() <= "я" or ch.lower() == "ё":
            if rng.random() < p_char:
                out.append(_typo_char(ch, rng))
                continue
        out.append(ch)
    return "".join(out)


def compose_user_text(
    core: str,
    rng: random.Random,
    use_synonyms: bool,
    use_colloquial: bool,
    use_style: bool,
    use_fixed_typos: bool,
    use_qwerty_typos: bool,
) -> tuple[str, str]:
    """Собирает финальный текст обращения из ядра.

    Возвращает (noisy_text, clean_text) — чистая версия нужна для fix #18
    (можно использовать как parallel corpus для SAGE-like спелл-коррекции).

    Fix #6 — style и preamble/suffix взаимоисключающие.
    """
    modified_core = core
    if use_synonyms:
        modified_core = apply_synonyms(modified_core, rng)

    if use_style:
        # стиль вместо преамбулы/суффикса
        clean = apply_style(modified_core, rng)
    else:
        preamble = rng.choice(PREAMBLES)
        suffix = rng.choice(SUFFIXES)
        clean = preamble + modified_core + suffix

    if use_colloquial:
        clean = apply_colloquial(clean, rng)

    clean = clean.strip()
    noisy = clean
    if use_fixed_typos:
        noisy = apply_fixed_typos(noisy, rng)
    if use_qwerty_typos:
        noisy = apply_qwerty_typos(noisy, rng)
    return noisy, clean

