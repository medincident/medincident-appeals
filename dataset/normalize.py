"""Нормализация formalized-таргетов: срезает канцелярские безличные зачины.

Проблема: эталоны формализации в шаблонах начинались с штампов
("Зафиксировано падение...", "Отмечается, что...", "Пациент подаёт сигнал:..."),
и seq2seq честно их воспроизводил вместо того, чтобы суммаризовать суть.

Эта функция убирает такие зачины, оставляя содержательную медицинскую фразу.
Срезаются ТОЛЬКО безличные регистрирующие обороты, после удаления которых
остаётся валидная номинативная фраза или клауза. Репортивные обороты с предлогом
("сообщает о...", "заявляет о...") НЕ трогаем — иначе фраза начнётся с предлога.

Применяется в генераторе (dataset/generator.py) ко всем formalized-таргетам.
Для инференса в nlp-service есть автономная копия (seq2seq/model.py), чтобы
сервис не зависел от пакета dataset во время выполнения.
"""

from __future__ import annotations

import re

# Безличные/репортивные зачины-штампы. Регистронезависимо, только в начале строки.
_OPENERS = [
    r"зафиксирован[оаы]?",
    r"зарегистрирован[оаы]?",
    r"отмечен[оаы]?",
    r"отмечается(?:,?\s*что)?(?:\s+у\s+пациент(?:а|ки))?",
    r"выявлен[оаы]?",
    r"установлен[оаы]?",
    r"констатирован[оаы]?",
    r"пациент(?:ка)?\s+подаёт\s+сигнал(?:\s+бедствия)?",
    # репортивные — срезаем только если дальше НЕ предлог "о/об" (иначе остаётся "О ...")
    r"пациент(?:ка)?\s+сообщает(?:,?\s*что)?(?!\s+о\b|\s+об\b)",
    r"пациент(?:ка)?\s+заявляет(?:,?\s*что)?(?!\s+о\b|\s+об\b)",
    r"пациент(?:ка)?\s+обращается\s+с",
]
_PAT = re.compile(r"^(?:%s)[\s:,]+" % "|".join(_OPENERS), re.IGNORECASE)


def normalize_formalized(text: str) -> str:
    """Срезает канцелярский зачин и капитализирует первую букву.

    Идемпотентна. Никогда не возвращает пустую строку: если после среза ничего
    не остаётся, возвращается последнее непустое состояние.
    """
    if not text:
        return text
    t = text.strip()
    while True:
        stripped = _PAT.sub("", t).strip()
        if not stripped or stripped == t:
            break
        t = stripped
    return t[0].upper() + t[1:] if t else text
